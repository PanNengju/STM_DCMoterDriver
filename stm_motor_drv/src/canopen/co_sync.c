/**
 * @file    co_sync.c
 * @brief   CANopen SYNC (同步对象) 实现
 *          SYNC Producer: 1ms 周期发送
 *          SYNC Consumer: 同步触发 PDO
 */

#include "co_sync.h"

/*===========================================================================
 * SYNC 初始化
 *===========================================================================*/
void co_sync_init(void)
{
    /* SYNC 无内部状态 */
}

/*===========================================================================
 * SYNC Producer — 发送 (1ms 周期)
 *
 * COB-ID: 0x080, Data: 无 (0字节) 或带计数器 (1字节)
 *===========================================================================*/
void co_sync_process(void)
{
    /* 发送 SYNC 帧 (0字节数据) */
    canopen_tx_frame(0x080, NULL, 0);
}

/*===========================================================================
 * SYNC Consumer — 接收回调
 *
 * 当作为从机时，主机发送 SYNC 触发本机同步 PDO
 *===========================================================================*/
void co_sync_rx_callback(void)
{
    /* 同步 PDO 发送已由 co_pdo_process_sync() 处理 */
}
